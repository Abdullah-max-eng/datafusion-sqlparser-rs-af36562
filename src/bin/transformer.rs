use sqlparser::parser::cypher::{cypher_to_sql_ast, cypher_to_sql_text, render_statements};
use std::io::Read;

fn main() {
    // Read the whole stdin (the Cypher text) into buf
    let mut buf = String::new();
    std::io::stdin().read_to_string(&mut buf).unwrap();

    // ===== STAGE A: Cypher -> provisional SQL string (your mapping) =====
    match cypher_to_sql_text(&buf) {
        Ok(provisional) => {
            eprintln!("========= STAGE A: YOUR MAPPING (Cypher → provisional SQL) =========");
            eprintln!("{}", provisional);
            eprintln!("=====================================================================");
        }
        Err(e) => eprintln!("(mapping skipped, because cypher_to_sql_text failed: {e})"),
    }

    // ===== STAGE B + C: Parse to AST, then pretty-print back to SQL =====
    match cypher_to_sql_ast(&buf) {
        Ok(stmts) => {
            eprintln!("========= STAGE B: AST generated by datafusion-sqlparser-rs =========");
            for s in &stmts {
                eprintln!("{:#?}", s);
            }
            eprintln!("=====================================================================");

            let sql = render_statements(&stmts);

            eprintln!("========= STAGE C: SQL regenerated FROM AST ==========================");
            eprintln!("{}", sql);
            eprintln!("=====================================================================");

            // Final output (stdout) – this is what the Go server consumes
            println!("{}->>>>>>>>>>>>>", sql);
        }
        Err(e) => {
            eprintln!("transform error: {e}");
            std::process::exit(2);
        }
    }
}
